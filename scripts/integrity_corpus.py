#!/usr/bin/env python3
"""Integrity corpus: public pull requests that modify test code (v0.24 Phase D).

Samples merged PRs from coding-agent accounts or markers and human-authored PRs
from the same repositories, pins them by SHA in tests/integrity/manifest.toml,
caches their test and gate file patches under the gitignored
`.integrity-corpus/`, prints them for blinded labeling, and reports prevalence
from tests/integrity/labels.toml.

    python3 scripts/integrity_corpus.py sample   # needs `gh` auth; writes manifest
    python3 scripts/integrity_corpus.py fetch    # caches patches for the manifest
    python3 scripts/integrity_corpus.py show ID  # test/gate hunks for labeling
    python3 scripts/integrity_corpus.py evaluate # run a RepoPilot build per PR
    python3 scripts/integrity_corpus.py report   # prevalence and catches, Wilson intervals
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

import integrity_corpus_eval as evaluation
import integrity_corpus_github as gh
import integrity_corpus_report as report
from integrity_corpus_paths import is_gate_file, is_test_file

REPO_ROOT = Path(__file__).resolve().parent.parent
CORPUS_DIR = REPO_ROOT / "tests" / "integrity"
MANIFEST = CORPUS_DIR / "manifest.toml"
LABELS = CORPUS_DIR / "labels.toml"
CACHE = REPO_ROOT / ".integrity-corpus"

WINDOW = ("2026-06-01", "2026-09-28")
AGENT_QUERIES = {
    "copilot": "author:app/copilot-swe-agent",
    "devin": "author:app/devin-ai-integration",
    "jules": "author:app/google-labs-jules",
    "claude-code": '"Generated with Claude Code" in:body',
    "codex": "label:codex",
}
MIN_STARS = 100
MAX_FILES = 60
PER_REPO = 2
SHOW_LINES = 160
STATUS = {"ADDED": "added", "DELETED": "removed", "MODIFIED": "modified", "RENAMED": "renamed", "COPIED": "added", "CHANGED": "modified"}


def load_manifest() -> list[dict]:
    if not MANIFEST.exists():
        return []
    return tomllib.loads(MANIFEST.read_text())["pr"]


def write_manifest(entries: list[dict]) -> None:
    lines = [
        "# Integrity corpus manifest (v0.24 Phase D). Generated by",
        "# `scripts/integrity_corpus.py sample`; pinned by SHA. Do not edit by hand.",
        f'# Window: merged PRs created {WINDOW[0]}..{WINDOW[1]}; repos >= {MIN_STARS} stars;',
        f"# <= {MAX_FILES} changed files; >= 1 modified or removed test file.",
        "",
    ]
    for entry in entries:
        lines.append("[[pr]]")
        for key in ("id", "group", "agent", "repo", "number", "base_sha", "head_sha", "language", "created"):
            value = entry[key]
            lines.append(f"{key} = {json.dumps(value)}")
        lines.append("")
    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text("\n".join(lines))


def qualifies(node: dict) -> dict | None:
    repo = node["repository"]
    if repo["isFork"] or repo["isArchived"] or repo["isPrivate"] or repo["stargazerCount"] < MIN_STARS:
        return None
    if not 0 < node["changedFiles"] <= MAX_FILES:
        return None
    files = [{"filename": f["path"], "status": STATUS[f["changeType"]]} for f in node["files"]["nodes"]]
    touched = [f for f in files if f["status"] in ("modified", "removed", "renamed") and is_test_file(f)]
    if not touched:
        return None
    return {
        "repo": repo["nameWithOwner"],
        "number": node["number"],
        "base_sha": node["baseRefOid"],
        "head_sha": node["headRefOid"],
        "language": ",".join(sorted({Path(f["filename"]).suffix.lstrip(".") for f in touched})),
        "created": node["createdAt"][:10],
        "user_type": (node.get("author") or {}).get("__typename", ""),
        "body": node.get("body") or "",
    }


def sample(per_agent: int) -> None:
    """Resumable: progress is appended to the gitignored cache as it is found,
    so a rate-limit stop loses nothing already sampled."""
    CACHE.mkdir(exist_ok=True)
    progress = CACHE / "sample-progress.jsonl"
    done_windows: set[tuple[str, str]] = set()
    picked: list[dict] = []
    if progress.exists():
        for line in progress.read_text().splitlines():
            record = json.loads(line)
            if record["type"] == "window":
                done_windows.add((record["agent"], record["span"]))
            else:
                picked.append(record["entry"])

    def remember(record: dict) -> None:
        with progress.open("a") as handle:
            handle.write(json.dumps(record) + "\n")

    seen = {(e["repo"], e["number"]) for e in picked}
    for agent, qualifier in AGENT_QUERIES.items():
        count = sum(1 for e in picked if e["agent"] == agent)
        for span in gh.windows(WINDOW, 2):
            if count >= per_agent:
                break
            if (agent, span) in done_windows:
                continue
            for node in gh.search_pr_nodes(f"is:pr is:merged review:approved {qualifier} created:{span}", pages=3):
                entry = qualifies(node)
                if entry is None or (entry["repo"], entry["number"]) in seen:
                    continue
                if sum(1 for e in picked if e["group"] == "agent" and e["repo"] == entry["repo"]) >= PER_REPO:
                    continue
                entry.update(group="agent", agent=agent)
                picked.append(entry)
                seen.add((entry["repo"], entry["number"]))
                remember({"type": "entry", "entry": entry})
                count += 1
                print(f"agent/{agent}: {entry['repo']}#{entry['number']}", file=sys.stderr, flush=True)
                if count >= per_agent:
                    break
            remember({"type": "window", "agent": agent, "span": span})
    for repo in sorted({e["repo"] for e in picked if e["group"] == "agent"}):
        if (f"human:{repo}", "all") in done_windows:
            continue
        count = sum(1 for e in picked if e["group"] == "human" and e["repo"] == repo)
        for node in gh.search_repo_human_prs(repo, WINDOW, list(AGENT_QUERIES.values())):
            if count >= PER_REPO:
                break
            entry = qualifies(node)
            if entry is None or entry["user_type"] != "User" or gh.has_agent_marker(entry["body"]):
                continue
            if (entry["repo"], entry["number"]) in seen:
                continue
            entry.update(group="human", agent="none")
            picked.append(entry)
            seen.add((entry["repo"], entry["number"]))
            remember({"type": "entry", "entry": entry})
            count += 1
            print(f"human: {repo}#{entry['number']}", file=sys.stderr, flush=True)
        remember({"type": "window", "agent": f"human:{repo}", "span": "all"})
    picked.sort(key=lambda e: (e["group"], e["repo"], e["number"]))
    for index, entry in enumerate(picked, start=1):
        entry["id"] = f"ic-{index:03d}"
    write_manifest(picked)
    print(f"wrote {len(picked)} PRs to {MANIFEST.relative_to(REPO_ROOT)}")


def fetch() -> None:
    CACHE.mkdir(exist_ok=True)
    for entry in load_manifest():
        path = CACHE / f"{entry['id']}.json"
        if path.exists():
            continue
        files = gh.pr_files(entry["repo"], entry["number"])
        meta = gh.pr_meta(entry["repo"], entry["number"])
        keep = [f for f in files if is_test_file(f) or is_gate_file(f["filename"])]
        path.write_text(json.dumps({"title": meta["title"], "files": keep, "all_files": [f["filename"] for f in files]}))
        print(f"cached {entry['id']}", file=sys.stderr)


ADDITIVE_VOCABULARY = re.compile(
    r"skip|\.only|fit\(|fdescribe|xfail|xit\(|todo|ignore|noqa|nolint|eslint-disable|ts-expect|ts-nocheck"
    r"|allow\(|pragma|continue-on-error|allow_failure|fail_under|threshold|strict|deselect|\|\| true|exit 0",
    re.IGNORECASE,
)


def show(corpus_id: str, compact: bool = False) -> None:
    entry = next((e for e in load_manifest() if e["id"] == corpus_id), None)
    if entry is None:
        sys.exit(f"unknown corpus id {corpus_id}")
    data = json.loads((CACHE / f"{corpus_id}.json").read_text())
    print(f"# {corpus_id} [{entry['group']}/{entry['agent']}] {entry['repo']}#{entry['number']} — {data['title']}")
    others = [f for f in data["all_files"] if not any(f == k["filename"] for k in data["files"])]
    print(f"# other changed files ({len(others)}): " + ", ".join(others)[:400])
    for f in data["files"]:
        print(f"## {f['status']} {f['filename']} (+{f['additions']} -{f['deletions']})")
        patch = (f.get("patch") or "(patch unavailable: file too large)").splitlines()
        if compact:
            patch = compact_patch(patch)
        print("\n".join(patch[:SHOW_LINES]))
        if len(patch) > SHOW_LINES:
            print(f"... ({len(patch) - SHOW_LINES} more lines not shown)")


def compact_patch(lines: list[str]) -> list[str]:
    """Hunks with removals in full; additive hunks reduced to lines that use
    skip/focus/suppression/gate vocabulary. Context lines are dropped."""
    hunks, current = [], []
    for line in lines:
        if line.startswith("@@") and current:
            hunks.append(current)
            current = []
        current.append(line)
    if current:
        hunks.append(current)
    out, hidden = [], 0
    for hunk in hunks:
        changed = [line for line in hunk[1:] if line.startswith(("+", "-"))]
        if any(line.startswith("-") for line in changed):
            out.append(hunk[0])
            out.extend(changed)
        else:
            flagged = [line for line in changed if ADDITIVE_VOCABULARY.search(line)]
            if flagged:
                out.append(hunk[0] + " (additive; vocabulary lines only)")
                out.extend(flagged)
            else:
                hidden += 1
    if hidden:
        out.append(f"({hidden} purely additive hunk(s) without skip/suppression/gate vocabulary hidden)")
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sample")
    s.add_argument("--per-agent", type=int, default=20)
    sub.add_parser("fetch")
    sh = sub.add_parser("show")
    sh.add_argument("ids", nargs="+")
    sh.add_argument("--compact", action="store_true")
    sub.add_parser("report")
    ev = sub.add_parser("evaluate")
    ev.add_argument("--bin", type=Path, default=REPO_ROOT / "target" / "release" / "repopilot")
    args = parser.parse_args()
    if args.cmd == "sample":
        sample(args.per_agent)
    elif args.cmd == "fetch":
        fetch()
    elif args.cmd == "show":
        for corpus_id in args.ids:
            show(corpus_id, compact=args.compact)
            print()
    elif args.cmd == "evaluate":
        evaluation.evaluate(load_manifest(), CACHE, args.bin)
    else:
        results = {
            path.stem: json.loads(path.read_text()) for path in sorted((CACHE / "results").glob("*.json"))
        }
        labels = tomllib.loads(LABELS.read_text()) if LABELS.exists() else {}
        print(report.render(load_manifest(), labels, results))


if __name__ == "__main__":
    main()
